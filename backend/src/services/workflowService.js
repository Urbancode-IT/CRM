const { prisma } = require('../config/db');
const emailService = require('./emailService');
const messagingService = require('./messagingService');

function entityId(obj) {
  return obj?.id ?? obj?._id ?? null;
}

function recordLabel(record) {
  if (!record || typeof record !== 'object') return null;
  const fromValues = record.values && typeof record.values === 'object' ? record.values : null;
  const name =
    record.name ||
    fromValues?.name ||
    record.title ||
    fromValues?.title ||
    record.email ||
    fromValues?.email ||
    null;
  return name ? String(name).trim() : null;
}

function matchCondition(record, condition) {
  if (!condition?.fieldKey) return true;
  const value = record?.[condition.fieldKey] ?? record?.values?.[condition.fieldKey];
  switch (condition.operator) {
    case 'eq':
      return value == condition.value;
    case 'neq':
      return value != condition.value;
    case 'gt':
      return Number(value) > Number(condition.value);
    case 'lt':
      return Number(value) < Number(condition.value);
    case 'contains':
      return String(value || '').toLowerCase().includes(String(condition.value || '').toLowerCase());
    default:
      return true;
  }
}

async function resolveNotifyRecipients(tenantId, config) {
  if (config?.to) return [String(config.to)];
  const memberships = await prisma.membership.findMany({
    where: {
      tenantId,
      status: 'active',
      role: { in: ['owner', 'admin'] },
    },
    include: { user: { select: { email: true } } },
  });
  return memberships.map((m) => m.user?.email).filter(Boolean);
}

function buildTaskTitle(action, wf, label) {
  const base = (action.config?.title || '').trim() || `Follow up: ${wf.name}`;
  if (!label) return base;
  if (base.toLowerCase().includes(label.toLowerCase())) return base;
  return `${base} — ${label}`;
}

function buildTaskDescription(action, wf, trigger, record, label) {
  const parts = [];
  const configured = (action.config?.description || action.config?.message || '').trim();
  if (configured) parts.push(configured);
  else parts.push(`Auto task from workflow "${wf.name}" (${trigger}).`);

  if (label) parts.push(`Record: ${label}`);
  if (record?.phone) parts.push(`Phone: ${record.phone}`);
  if (record?.parentPhone) {
    const parent = [record.parentName, record.parentPhone].filter(Boolean).join(' · ');
    parts.push(`Parent: ${parent}`);
  }
  if (record?.batch) parts.push(`Batch: ${record.batch}`);
  if (record?.grade) parts.push(`Grade: ${record.grade}`);

  return parts.join('\n');
}

async function runWorkflows({ tenantId, moduleId, systemKey, trigger, record, user }) {
  if (!tenantId || !trigger) return;

  let module = null;
  if (moduleId) {
    module = await prisma.customModule.findFirst({ where: { id: String(moduleId), tenantId } });
  } else if (systemKey) {
    module = await prisma.customModule.findFirst({ where: { tenantId, systemKey } });
  }

  // Match module-specific workflows and "Any / system modules" (moduleId null).
  const where = {
    tenantId,
    isActive: true,
    trigger,
    OR: module ? [{ moduleId: module.id }, { moduleId: null }] : [{ moduleId: null }],
  };

  const tenant = await prisma.tenant.findUnique({ where: { id: tenantId } });
  const workflows = await prisma.workflow.findMany({ where });
  const label = recordLabel(record);
  const recordId = entityId(record);
  const isStudentContext =
    systemKey === 'students' || module?.systemKey === 'students';

  for (const wf of workflows) {
    const conditions = Array.isArray(wf.conditions) ? wf.conditions : [];
    const actions = Array.isArray(wf.actions) ? wf.actions : [];
    const ok = conditions.every((c) => matchCondition(record, c));
    if (!ok) continue;

    for (const action of actions) {
      if (action.type === 'create_task') {
        const data = {
          tenantId,
          title: buildTaskTitle(action, wf, label),
          description: buildTaskDescription(action, wf, trigger, record, label),
          priority: action.config?.priority || 'medium',
          status: 'pending',
          assignedTo: user?.name || 'Staff',
          autoGenerated: true,
        };
        if (isStudentContext && recordId) {
          data.relatedStudentId = String(recordId);
        }
        await prisma.task.create({ data });
      }

      if (action.type === 'notify') {
        const title = action.config?.title || wf.name;
        const message =
          action.config?.message ||
          `Workflow "${wf.name}" fired on ${trigger}${label ? ` for ${label}` : ''} (${tenant?.name || 'workspace'}).`;
        const recipients = await resolveNotifyRecipients(tenantId, action.config);
        for (const to of recipients) {
          await emailService.sendWorkflowNotifyEmail(to, {
            title,
            message,
            workspaceName: tenant?.name,
          });
        }
        if (action.config?.phone) {
          await messagingService.sendWhatsApp({
            to: action.config.phone,
            body: `${title}\n${message}`,
          });
        }
      }

      if (action.type === 'update_field') {
        const fieldKey = action.config?.fieldKey;
        if (!fieldKey || !recordId) continue;
        const nextValue =
          action.config?.value !== undefined ? action.config.value : action.config?.setValue;
        const values = { ...(record.values || {}) };
        values[fieldKey] = nextValue;
        const updaterId = entityId(user);
        await prisma.record.updateMany({
          where: { id: String(recordId), tenantId },
          data: { values, ...(updaterId ? { updatedById: String(updaterId) } : {}) },
        });
        if (record.values) record.values = values;
        else record[fieldKey] = nextValue;
      }
    }
  }
}

module.exports = { runWorkflows, matchCondition, recordLabel };
