function daysAgo(n) {
  const d = new Date();
  d.setDate(d.getDate() - n);
  d.setHours(0, 0, 0, 0);
  return d;
}

async function wipeTenantDemo(tenantId) {
  const students = await prisma.student.findMany({
    where: { tenantId },
    select: { id: true },
  });
  const ids = students.map((s) => s.id);
  await prisma.$transaction([
    prisma.payment.deleteMany({ where: { tenantId } }),
    prisma.attendance.deleteMany({ where: { tenantId } }),
    prisma.task.deleteMany({ where: { tenantId, autoGenerated: false } }),
    prisma.student.deleteMany({ where: { tenantId } }),
  ]);
  return ids;
}

async function insertDemoData(tenantId) {
  const students = await prisma.$transaction(
    DEMO_STUDENTS.map((s) => prisma.student.create({ data: { ...s, tenantId } }))
  );

  const now = new Date();
  const thisMonth = now.getMonth() + 1;
  const thisYear = now.getFullYear();
  const lastMonthDate = new Date(thisYear, thisMonth - 2, 1);
  const lastMonth = lastMonthDate.getMonth() + 1;
  const lastMonthYear = lastMonthDate.getFullYear();

  const payments = [];
  students.forEach((s, i) => {
    if (s.status !== 'active') return;

    payments.push({
      tenantId,
      studentId: s.id,
      amount: s.monthlyFee,
      month: lastMonth,
      year: lastMonthYear,
      dueDate: new Date(lastMonthYear, lastMonth - 1, 5),
      paidDate: new Date(lastMonthYear, lastMonth - 1, 3),
      status: 'paid',
      method: 'online',
      receiptSent: true,
    });

    const pattern = i % 3;
    if (pattern === 0) {
      payments.push({
        tenantId,
        studentId: s.id,
        amount: s.monthlyFee,
        month: thisMonth,
        year: thisYear,
        dueDate: new Date(thisYear, thisMonth - 1, 5),
        paidDate: new Date(thisYear, thisMonth - 1, 4),
        status: 'paid',
        method: 'cash',
        receiptSent: true,
      });
    } else if (pattern === 1) {
      payments.push({
        tenantId,
        studentId: s.id,
        amount: s.monthlyFee,
        month: thisMonth,
        year: thisYear,
        dueDate: new Date(thisYear, thisMonth - 1, 5),
        status: 'pending',
        method: 'cash',
      });
    } else {
      payments.push({
        tenantId,
        studentId: s.id,
        amount: s.monthlyFee,
        month: thisMonth,
        year: thisYear,
        dueDate: daysAgo(10),
        status: 'overdue',
        method: 'cash',
        reminderCount: 1,
        lastReminderSentAt: daysAgo(2),
      });
    }
  });
  await prisma.payment.createMany({ data: payments });

  const attendanceStatuses = ['present', 'present', 'present', 'late', 'absent'];
  const attendance = [];
  students
    .filter((s) => s.status === 'active')
    .forEach((s, i) => {
      for (let day = 0; day < 14; day++) {
        if (day % 7 === 0 && day !== 0) continue;
        attendance.push({
          tenantId,
          studentId: s.id,
          date: daysAgo(day),
          status: attendanceStatuses[(i + day) % attendanceStatuses.length],
          markedBy: 'Tutor Manager',
        });
      }
    });
  await prisma.attendance.createMany({ data: attendance });

  const tasks = [
    {
      tenantId,
      title: 'Send progress report to parents',
      description: 'Weekly summary email covering attendance and test scores.',
      assignedTo: 'Tutor',
      priority: 'medium',
      status: 'pending',
      recurring: true,
      recurrencePattern: 'weekly',
    },
    {
      tenantId,
      title: 'Prepare Batch A mock test',
      description: 'Maths + Physics mock test for upcoming unit exam.',
      relatedStudentId: students[0].id,
      dueDate: daysAgo(-3),
      priority: 'high',
      status: 'pending',
    },
    {
      tenantId,
      title: 'Follow up on overdue fee',
      description: "Call parent regarding this month's pending payment.",
      relatedStudentId: students[2].id,
      dueDate: daysAgo(-1),
      priority: 'high',
      status: 'in_progress',
    },
    {
      tenantId,
      title: "Review Meena's English essay",
      relatedStudentId: students[3].id,
      dueDate: daysAgo(1),
      priority: 'low',
      status: 'completed',
    },
    {
      tenantId,
      title: 'Order new practice worksheets',
      priority: 'low',
      status: 'pending',
      dueDate: daysAgo(-7),
    },
  ];
  await prisma.task.createMany({ data: tasks });

  return {
    seeded: true,
    students: students.length,
    payments: payments.length,
    attendance: attendance.length,
    tasks: tasks.length,
  };
}

/** Onboarding-safe: only seed when this tenant has no students yet. */
async function loadSampleData(tenantId) {
  if (!tenantId) {
    return { seeded: false, reason: 'missing_tenant' };
  }
  const existingCount = await prisma.student.count({ where: studentWhere({ tenantId }) });
  if (existingCount > 0) {
    return { seeded: false, reason: 'already_has_data' };
  }
  return insertDemoData(tenantId);
}

/** CLI: wipe then recreate demo data for one tenant. */
async function forceReloadSampleData(tenantId) {
  if (!tenantId) throw new Error('tenantId required');
  await wipeTenantDemo(tenantId);
  return insertDemoData(tenantId);
}

module.exports = { loadSampleData, forceReloadSampleData };
