function daysAgo(n) {
  const d = new Date();
  d.setDate(d.getDate() - n);
  d.setHours(0, 0, 0, 0);
  return d;
}

async function seedDemoData() {
  await connectDB();

  await Promise.all([
    Payment.deleteMany({}),
    Attendance.deleteMany({}),
    Task.deleteMany({ autoGenerated: false }),
    Student.deleteMany({}),
  ]);

  const students = await Student.insertMany(DEMO_STUDENTS);
  console.log(`[seed:demo] created ${students.length} students`);

  const now = new Date();
  const thisMonth = now.getMonth() + 1;
  const thisYear = now.getFullYear();
  const lastMonthDate = new Date(thisYear, thisMonth - 2, 1);
  const lastMonth = lastMonthDate.getMonth() + 1;
  const lastMonthYear = lastMonthDate.getFullYear();

  const payments = [];
  students.forEach((s, i) => {
    if (s.status !== 'active') return;

    // Last month: everyone paid.
    payments.push({
      student: s._id,
      amount: s.monthlyFee,
      month: lastMonth,
      year: lastMonthYear,
      dueDate: new Date(lastMonthYear, lastMonth - 1, 5),
      paidDate: new Date(lastMonthYear, lastMonth - 1, 3),
      status: 'paid',
      method: 'online',
      receiptSent: true,
    });

    // This month: mix of paid / pending / overdue for a realistic dashboard.
    const pattern = i % 3;
    if (pattern === 0) {
      payments.push({
        student: s._id,
        amount: s.monthlyFee,
        month: thisMonth,
        year: thisYear,
        dueDate: new Date(thisYear, thisMonth - 1, 5),
        paidDate: new Date(thisYear, thisMonth - 1, 4),
        status: 'paid',
        method: 'cash',
        receiptSent: true,
      });
    } else if (pattern === 1) {
      payments.push({
        student: s._id,
        amount: s.monthlyFee,
        month: thisMonth,
        year: thisYear,
        dueDate: new Date(thisYear, thisMonth - 1, 5),
        status: 'pending',
        method: 'cash',
      });
    } else {
      payments.push({
        student: s._id,
        amount: s.monthlyFee,
        month: thisMonth,
        year: thisYear,
        dueDate: daysAgo(10),
        status: 'overdue',
        method: 'cash',
        reminderCount: 1,
        lastReminderSentAt: daysAgo(2),
      });
    }
  });
  await Payment.insertMany(payments);
  console.log(`[seed:demo] created ${payments.length} payment records`);

  const attendanceStatuses = ['present', 'present', 'present', 'late', 'absent'];
  const attendance = [];
  students
    .filter((s) => s.status === 'active')
    .forEach((s, i) => {
      for (let day = 0; day < 14; day++) {
        if (day % 7 === 0 && day !== 0) continue; // skip one day a week (holiday)
        attendance.push({
          student: s._id,
          date: daysAgo(day),
          status: attendanceStatuses[(i + day) % attendanceStatuses.length],
          markedBy: 'Tutor Manager',
        });
      }
    });
  await Attendance.insertMany(attendance);
  console.log(`[seed:demo] created ${attendance.length} attendance records`);

  const tasks = [
    {
      title: 'Send progress report to parents',
      description: 'Weekly summary email covering attendance and test scores.',
      assignedTo: 'Tutor',
      priority: 'medium',
      status: 'pending',
      recurring: true,
      recurrencePattern: 'weekly',
    },
    {
      title: 'Prepare Batch A mock test',
      description: 'Maths + Physics mock test for upcoming unit exam.',
      relatedStudent: students[0]._id,
      dueDate: daysAgo(-3),
      priority: 'high',
      status: 'pending',
    },
    {
      title: 'Follow up on overdue fee',
      description: 'Call parent regarding this month\'s pending payment.',
      relatedStudent: students[2]._id,
      dueDate: daysAgo(-1),
      priority: 'high',
      status: 'in_progress',
    },
    {
      title: 'Review Meena\'s English essay',
      relatedStudent: students[3]._id,
      dueDate: daysAgo(1),
      priority: 'low',
      status: 'completed',
    },
    {
      title: 'Order new practice worksheets',
      priority: 'low',
      status: 'pending',
      dueDate: daysAgo(-7),
    },
  ];
  await Task.insertMany(tasks);
  console.log(`[seed:demo] created ${tasks.length} tasks`);

  console.log('[seed:demo] done');
  process.exit(0);
}

seedDemoData().catch((err) => {
  console.error('[seed:demo] failed', err);
  process.exit(1);
});
