function getCatalogItem(id) {
  return MODULE_CATALOG.find((m) => m.id === id) || null;
}

function planUnlocked(planCode, minPlan) {
  const have = PLAN_RANK[planCode] ?? 0;
  const need = PLAN_RANK[minPlan] ?? 0;
  return have >= need;
}

