const PDFDocument = require('pdfkit');

function buildReceiptPdf({
  workspace = 'User',
  studentName = '',
  amount = 0,
  month,
  year,
  paidDate,
  method = '',
  receiptId = '',
}) {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'A4', margin: 50 });
    const chunks = [];
    doc.on('data', (c) => chunks.push(c));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);

    const monthName = new Date(year, (month || 1) - 1, 1).toLocaleString('default', {
      month: 'long',
    });
    const paidLabel = paidDate ? new Date(paidDate).toLocaleDateString('en-IN') : '—';
    const amountLabel = `₹${Number(amount || 0).toLocaleString('en-IN')}`;

    doc.fontSize(20).fillColor('#0f172a').text(workspace, { continued: false });
    doc.moveDown(0.3);
    doc.fontSize(11).fillColor('#64748b').text('Fee receipt');
    doc.moveDown(1);
    doc.fontSize(28).fillColor('#0f172a').text(amountLabel);
    doc.moveDown(1.2);

    const rows = [
      ['Student', studentName || '—'],
      ['Period', `${monthName} ${year}`],
      ['Paid on', paidLabel],
      ['Method', method || '—'],
      ['Receipt ID', String(receiptId)],
    ];

    rows.forEach(([label, value]) => {
      doc.fontSize(11).fillColor('#64748b').text(label, { continued: false, width: 140 });
      doc
        .moveUp()
        .fillColor('#0f172a')
        .text(value, 190, doc.y, { width: 320 });
      doc.moveDown(0.55);
    });

    doc.moveDown(2);
    doc.fontSize(9).fillColor('#94a3b8').text('Generated by User');
    doc.end();
  });
}

module.exports = { buildReceiptPdf };
