const { prisma } = require('../config/db');
const { studentWhere, notificationEmail } = require('../utils/studentQuery');
const emailService = require('../services/emailService');
const messagingService = require('../services/messagingService');

function monthDueDate(year, month) {
  const day = Math.min(Number(process.env.FEE_DUE_DAY) || 5, 28);
  return new Date(year, month - 1, day);
}

async function generateMonthlyPaymentRecords() {
  const now = new Date();
  const month = now.getMonth() + 1;
  const year = now.getFullYear();

  const activeStudents = await prisma.student.findMany({
    where: studentWhere({ status: 'active' }),
  });
  let created = 0;

  for (const student of activeStudents) {
    const exists = await prisma.payment.findFirst({
      where: {
        tenantId: student.tenantId,
        studentId: student.id,
        month,
        year,
      },
      select: { id: true },
    });
    if (exists) continue;

    await prisma.payment.create({
      data: {
        tenantId: student.tenantId,
        studentId: student.id,
        amount: student.monthlyFee,
        month,
        year,
        dueDate: monthDueDate(year, month),
        status: 'pending',
        autoGenerated: true,
      },
    });
    created += 1;
  }

  if (created) console.log(`[reminderJob] generated ${created} monthly payment record(s)`);
  return created;
}

async function flagAndSendOverdueReminders() {
  const graceDays = Number(process.env.OVERDUE_GRACE_DAYS) || 2;
  const cooldownDays = Number(process.env.REMINDER_COOLDOWN_DAYS) || 3;
  const now = new Date();
  const graceCutoff = new Date(now);
  graceCutoff.setDate(graceCutoff.getDate() - graceDays);

  const overdueCandidates = await prisma.payment.findMany({
    where: {
      status: { in: ['pending', 'overdue'] },
      dueDate: { lt: graceCutoff },
      student: studentWhere(),
    },
    include: { student: true },
  });

  let flagged = 0;
  let emailed = 0;

  for (const payment of overdueCandidates) {
    const data = {};

    if (payment.status !== 'overdue') {
      data.status = 'overdue';
      flagged += 1;
    }

    const dueForReminder =
      !payment.lastReminderSentAt ||
      (now - new Date(payment.lastReminderSentAt)) / (1000 * 60 * 60 * 24) >= cooldownDays;

    if (dueForReminder && payment.student) {
      const to = notificationEmail(payment.student);
      const result = await emailService.sendOverdueReminderEmail(to, {
        studentName: payment.student.name,
        amount: payment.amount,
        month: payment.month,
        year: payment.year,
        dueDate: payment.dueDate,
      });
      const monthName = new Date(payment.year, payment.month - 1, 1).toLocaleString('default', {
        month: 'long',
      });
      const wa = await messagingService.notifyParent({
        phone: payment.student.parentPhone || payment.student.phone,
        email: null,
        subject: `Fee overdue · ${monthName} ${payment.year}`,
        message: `Hi, fee of ₹${payment.amount} for ${payment.student.name} is overdue (due ${new Date(payment.dueDate).toLocaleDateString()}). Please pay at the earliest.`,
        prefer: 'whatsapp',
      });
      const anySent = result.sent || wa.some((r) => r.sent);
      if (anySent) {
        data.lastReminderSentAt = now;
        data.reminderCount = (payment.reminderCount || 0) + 1;
        emailed += 1;
      }
    }

    if (Object.keys(data).length) {
      await prisma.payment.update({ where: { id: payment.id }, data });
    }
  }

  if (flagged || emailed) {
    console.log(`[reminderJob] flagged ${flagged} overdue payment(s), emailed ${emailed} reminder(s)`);
  }
  return { flagged, emailed };
}

async function runPaymentAutomation() {
  await generateMonthlyPaymentRecords();
  await flagAndSendOverdueReminders();
}

module.exports = { runPaymentAutomation, generateMonthlyPaymentRecords, flagAndSendOverdueReminders };
