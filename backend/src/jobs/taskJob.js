const { prisma } = require('../config/db');

const PATTERN_DAYS = { daily: 1, weekly: 7, monthly: 30 };

async function generateRecurringTasks() {
  const templates = await prisma.task.findMany({ where: { recurring: true } });
  const now = new Date();
  let created = 0;

  for (const template of templates) {
    const intervalDays = PATTERN_DAYS[template.recurrencePattern] || 1;
    const last = template.lastGeneratedAt ? new Date(template.lastGeneratedAt) : null;
    const dueForGeneration = !last || (now - last) / (1000 * 60 * 60 * 24) >= intervalDays;
    if (!dueForGeneration) continue;

    const dueDate = new Date(now);
    dueDate.setDate(dueDate.getDate() + 1);

    await prisma.$transaction([
      prisma.task.create({
        data: {
          tenantId: template.tenantId,
          title: template.title,
          description: template.description,
          relatedStudentId: template.relatedStudentId,
          assignedTo: template.assignedTo,
          dueDate,
          priority: template.priority,
          status: 'pending',
          recurring: false,
          autoGenerated: true,
        },
      }),
      prisma.task.update({
        where: { id: template.id },
        data: { lastGeneratedAt: now },
      }),
    ]);
    created += 1;
  }

  if (created) console.log(`[taskJob] auto-generated ${created} recurring task instance(s)`);
  return created;
}

module.exports = { generateRecurringTasks };
